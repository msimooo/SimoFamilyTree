const bcrypt = require('bcryptjs');
const pg = require('pg');

pg.types.setTypeParser(20, (value) => Number(value));

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL is required. Create a PostgreSQL database and set its connection string.');
}

const db = new pg.Pool({
  connectionString: process.env.DATABASE_URL,
  max: 5,
});

async function createSchema(queryable) {
  await queryable.query(`
    CREATE TABLE IF NOT EXISTS users (
      id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username      TEXT UNIQUE NOT NULL,
      password_hash TEXT NOT NULL,
      display_name  TEXT NOT NULL,
      role          TEXT NOT NULL CHECK(role IN ('admin','assistant')),
      created_at    BIGINT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS people (
      id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      first_name  TEXT NOT NULL,
      gender      TEXT NOT NULL CHECK(gender IN ('male','female')),
      father_id   BIGINT REFERENCES people(id) ON DELETE SET NULL,
      photo_data  BYTEA,
      photo_mime  TEXT,
      created_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
      created_at  BIGINT NOT NULL,
      updated_at  BIGINT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS settings (
      key   TEXT PRIMARY KEY,
      value TEXT NOT NULL
    );

    CREATE INDEX IF NOT EXISTS idx_people_father ON people(father_id);
  `);

  await queryable.query(
    "INSERT INTO settings (key, value) VALUES ('public_tree_enabled', '0') ON CONFLICT (key) DO NOTHING"
  );
}

async function initializeDatabase() {
  await createSchema(db);

  const { rows } = await db.query('SELECT COUNT(*) AS count FROM users');
  if (Number(rows[0].count) === 0) {
    const hash = bcrypt.hashSync('admin123', 10);
    await db.query(
      `INSERT INTO users (username, password_hash, display_name, role, created_at)
       VALUES ($1, $2, $3, $4, $5)`,
      ['admin', hash, 'Administrator', 'admin', Date.now()]
    );

    console.log('Default administrator account created: username: admin, password: admin123');
    console.log('Please log in and change this password.');
  }
}

async function isPublicTreeEnabled() {
  const { rows } = await db.query("SELECT value FROM settings WHERE key = 'public_tree_enabled'");
  return rows[0] && rows[0].value === '1';
}

module.exports = { db, createSchema, initializeDatabase, isPublicTreeEnabled };
